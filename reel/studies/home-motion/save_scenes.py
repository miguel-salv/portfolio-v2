"""Packed editable scene anchors, without modifying original source .blend files."""
from pathlib import Path
import sys,json,hashlib
sys.path.insert(0,str(Path(__file__).resolve().parent))
import render as r

revision=hashlib.sha256((r.SOURCE/'render.py').read_bytes()).hexdigest()
r.bpy.context.preferences.filepaths.save_version=0
for name,shot,frame in [('matcher-inspection','shaft-to-drive',0),('shaft-match','shaft-to-drive',44),('vehicle-floor','shaft-to-drive',88),('robot-tiles','bottle-collect',119)]:
    ctx=r.setup(shot,'landscape',64);scene=ctx['scene']
    scene.render.resolution_x=1920;scene.render.resolution_y=1200
    fm=r.state(ctx,frame)
    meta=r.metadata(ctx,1,[fm],64,(1920,1200));meta.update(anchor=name,sourceLogicalFrame=frame,renderRevision=revision,generator='reel/studies/home-motion/save_scenes.py',scope='Editable single-frame final scene anchor. Full cinematic motion is generated by render.py from immutable source libraries; this file is not a keyed film timeline.')
    if name=='vehicle-floor':
        meta['foregroundEndpoint']=r.state(ctx,119)
        r.state(ctx,frame)
    scene['home_motion_anchor']=json.dumps({'name':name,'sourceLogicalFrame':frame,'renderRevision':revision,'generator':meta['generator']})
    r.bpy.ops.file.pack_all()
    r.bpy.ops.wm.save_as_mainfile(filepath=str(r.SOURCE/f'{name}.blend'),compress=True)
    (r.SOURCE/f'{name}.blend.json').write_text(json.dumps(meta,indent=2)+'\n')
    print('PACKED_STUDY_SOURCE',name,flush=True)
